const dictionary = new Map(entries.map(([vi, en, th]) => [vi, { vi, en, th }]));

export function normalizeLanguage(language) {
  return languages.includes(language) ? language : "vi";
}

// Translate only known copy. Custom live configuration remains authoritative.
export function translate(text, language) {
  return dictionary.get(text)?.[normalizeLanguage(language)] ?? text;
}

export function hasTranslation(text) {
  return dictionary.has(text);
}
